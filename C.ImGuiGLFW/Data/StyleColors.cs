namespace C.ImGuiGLFW.Data;

/// <summary>
/// Represents the available style color themes for the ImGui interface.
/// </summary>
/// <remarks>
/// These styles correspond to predefined ImGui color schemes and can be used to set the visual appearance of the UI.
/// </remarks>
public enum StyleColors
{
    /// <summary>
    /// Dark color theme, suitable for low-light environments.
    /// </summary>
    Dark,

    /// <summary>
    /// Light color theme, suitable for bright environments.
    /// </summary>
    Light,

    /// <summary>
    /// Classic color theme, the original ImGui style.
    /// </summary>
    Classic,
}
